function ChecksPanel({ report, selectedFindingFingerprints, onToggleFinding, onCreatePrompt }: { report: ScanReport; selectedFindingFingerprints: Set<string>; onToggleFinding: (fingerprint: string) => void; onCreatePrompt: (fingerprint: string) => void }) {
  const [query, setQuery] = useState('');
  const [statusFilter, setStatusFilter] = useState<'all' | CheckStatus>('all');
  const [severityFilter, setSeverityFilter] = useState<'all' | Severity>('all');
  const visibleChecks = useMemo(() => {
    const normalized = query.trim().toLowerCase();
    return report.checks.filter((check) => {
      const matchesStatus = statusFilter === 'all' || check.status === statusFilter;
      const matchesSeverity = severityFilter === 'all' || check.severity === severityFilter || check.findings.some((finding) => finding.severity === severityFilter);
      const searchable = [check.title, check.ruleId, ...check.findings.flatMap((finding) => [finding.title, finding.message, finding.location?.path ?? ''])].join(' ').toLowerCase();
      return matchesStatus && matchesSeverity && (!normalized || searchable.includes(normalized));
    });
  }, [query, report.checks, severityFilter, statusFilter]);
  const hasFilters = query.trim().length > 0 || statusFilter !== 'all' || severityFilter !== 'all';
  const clearFilters = () => { setQuery(''); setStatusFilter('all'); setSeverityFilter('all'); };

  return (
    <section className="panel checks-panel" id="checks" aria-labelledby="checks-heading">
      <div className="panel-heading checks-heading">
        <div><p className="eyebrow">Rule-by-rule review</p><h2 id="checks-heading">Checks <span className="heading-count">{visibleChecks.length}/{report.checks.length}</span></h2></div>
        <span className="icon-badge" aria-hidden="true">✓</span>
      </div>
       <div className="filter-bar" aria-label="Filter checks">
        <label className="search-field"><span className="sr-only">Search checks</span><span aria-hidden="true">⌕</span><input value={query} onChange={(event) => setQuery(event.target.value)} placeholder="Search checks or evidence" /></label>
        <label><span className="sr-only">Filter by status</span><select value={statusFilter} onChange={(event) => setStatusFilter(event.target.value as 'all' | CheckStatus)}><option value="all">All statuses</option><option value="passed">Passed</option><option value="finding">Findings</option><option value="not_checked">Not checked</option><option value="not_applicable">Not applicable</option></select></label>
        <label><span className="sr-only">Filter by severity</span><select value={severityFilter} onChange={(event) => setSeverityFilter(event.target.value as 'all' | Severity)}><option value="all">All severities</option><option value="error">Error</option><option value="warning">Warning</option><option value="info">Info</option></select></label>
       </div>
       <div className="filter-summary" aria-live="polite">
         <span><strong>{visibleChecks.length}</strong> of {report.checks.length} checks shown</span>
         {hasFilters && <button className="filter-reset" type="button" onClick={clearFilters}>Reset filters <span aria-hidden="true">×</span></button>}
       </div>
       {hasFilters && <div className="active-filters" aria-label="Active filters">
         {query.trim() && <span className="filter-chip">Search: <strong>{query.trim()}</strong></span>}
         {statusFilter !== 'all' && <span className="filter-chip">Status: <strong>{statusLabels[statusFilter]}</strong></span>}
         {severityFilter !== 'all' && <span className="filter-chip">Severity: <strong>{severityLabels[severityFilter]}</strong></span>}
       </div>}
       {visibleChecks.length > 0 ? <div className="check-stack">{visibleChecks.map((check) => <CheckCard key={check.ruleId} check={check} selectedFindingFingerprints={selectedFindingFingerprints} onToggleFinding={onToggleFinding} onCreatePrompt={onCreatePrompt} />)}</div> : <div className="no-results"><strong>No checks match those filters.</strong><button className="text-button" type="button" onClick={clearFilters}>Reset filters</button></div>}
    </section>
  );
}

