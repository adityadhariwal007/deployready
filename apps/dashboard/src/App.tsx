function NoticeBanner({ notice, noticeId = 'notice-heading' }: { notice: Notice; noticeId?: string }) {
  if (notice.status === 'idle') return null;
  const heading = notice.status === 'empty' ? 'No report loaded' : notice.status === 'malformed' ? 'Could not read this report' : 'Unsupported report';
  return (
    <section className={`notice-banner notice-${notice.status}`} role="alert" aria-labelledby={noticeId}>
      <div className="notice-icon" aria-hidden="true">{notice.status === 'empty' ? '○' : '!'}</div>
      <div>
        <h2 id={noticeId}>{heading}</h2>
        <p>{notice.message}</p>
        {notice.status === 'unsupported' && notice.errors.length > 0 && (
          <details className="validation-details">
            <summary>Show validation details</summary>
            <ul>
              {notice.errors.slice(0, 6).map((error) => <li key={error}>{error}</li>)}
            </ul>
          </details>
        )}
      </div>
    </section>
  );
}

